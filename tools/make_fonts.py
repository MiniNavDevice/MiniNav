#!/usr/bin/env python3
"""Builds main/ui_fonts.h: anti-aliased VLW fonts (the format LovyanGFX's loadFont() reads) from
Nunito (SIL OFL, tools/fonts/). Re-run after changing sizes or weights.

    python3 -m pip install --user pillow
    python3 tools/make_fonts.py
"""
import os, struct
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = os.path.join(HERE, "fonts", "Nunito.ttf")
OUT = os.path.join(HERE, "..", "main", "ui_fonts.h")
ASCII = "".join(chr(c) for c in range(0x20, 0x7F))

# name, pixel size, weight (200-1000), characters
FONTS = [
    ("FONT_HERO", 34, 800, " MiniNav"),          # boot animation title
    ("FONT_HEAD", 22, 800, " MiniNav"),          # status screen header
    ("FONT_TITLE", 18, 750, ASCII),              # status step title, ring number
    ("FONT_BODY", 13, 600, ASCII),               # detail lines, error pill
    ("FONT_SMALL", 11, 650, ASCII + "·×"),  # bottom hint
]


def vlw(px, weight, chars):
    f = ImageFont.truetype(TTF, px)
    f.set_variation_by_axes([weight])
    ascent, descent = f.getmetrics()
    glyphs = []
    for ch in sorted(set(chars), key=ord):
        adv = int(round(f.getlength(ch)))
        l, t, r, b = f.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        if ch == " " or w == 0 or h == 0:
            glyphs.append((ord(ch), 0, 0, adv, 0, 0, b""))
            continue
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor="ls")
        glyphs.append((ord(ch), h, w, adv, -t, l, im.tobytes()))
    data = struct.pack(">6i", len(glyphs), 11, px, 0, ascent, descent)
    for code, h, w, adv, dy, dx, _ in glyphs:
        data += struct.pack(">7i", code, h, w, adv, dy, dx, 0)
    for g in glyphs:
        data += g[6]
    return data


def main():
    out = ["// Generated by tools/make_fonts.py from Nunito (SIL Open Font License, tools/fonts/OFL.txt).",
           "// Anti-aliased VLW fonts for LovyanGFX loadFont(). Do not edit.", "#pragma once", "#include <stdint.h>", ""]
    for name, px, weight, chars in FONTS:
        data = vlw(px, weight, chars)
        out.append(f"// {px} px, weight {weight}, {len(set(chars))} glyphs, {len(data)} bytes")
        out.append(f"static const uint8_t {name}[] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append("")
        print(f"{name}: {len(data)} bytes")
    open(OUT, "w").write("\n".join(out))


if __name__ == "__main__":
    main()
