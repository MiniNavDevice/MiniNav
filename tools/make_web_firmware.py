#!/usr/bin/env python3
"""Builds the firmware files the install guide flashes (docs/flash/):
MiniNav.bin, one merged image for address 0x0, and MiniNav.bin.js, the same image as a script so
the guide's Install button also works when docs/index.html is opened straight from a clone
(browsers block fetch() on file:// pages, but load <script> files).

    idf.py build
    python3 tools/make_web_firmware.py      (run with the ESP-IDF environment active)
"""
import base64, hashlib, os, subprocess, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BUILD = os.path.join(ROOT, "build")
OUT = os.path.join(ROOT, "docs", "flash")

os.makedirs(OUT, exist_ok=True)
bin_path = os.path.join(OUT, "MiniNav.bin")
subprocess.check_call([sys.executable, "-m", "esptool", "--chip", "esp32s3", "merge_bin", "-o", bin_path,
                       "--flash_mode", "dio", "--flash_size", "16MB", "--flash_freq", "80m", "@flash_args"], cwd=BUILD)
data = open(bin_path, "rb").read()
with open(bin_path + ".js", "w") as f:
    f.write("// Generated by tools/make_web_firmware.py: docs/flash/MiniNav.bin as base64. Do not edit.\n")
    f.write('window.MININAV_FIRMWARE = {md5: "%s", size: %d, data: "%s"};\n'
            % (hashlib.md5(data).hexdigest(), len(data), base64.b64encode(data).decode()))
print("MiniNav.bin: %d bytes, md5 %s" % (len(data), hashlib.md5(data).hexdigest()))
